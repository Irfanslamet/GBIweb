CREATE TABLE IF NOT EXISTS users (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  email VARCHAR(190) NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_users_email (email)
);

CREATE TABLE IF NOT EXISTS players (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  name VARCHAR(100) NOT NULL,
  photo_url LONGTEXT NULL,
  is_active BOOLEAN NOT NULL DEFAULT TRUE,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  UNIQUE KEY uq_players_name (name)
);

CREATE TABLE IF NOT EXISTS matches (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  match_type ENUM('SINGLE', 'DOUBLE') NOT NULL,
  match_date DATE NOT NULL,
  notes VARCHAR(255) NULL,
  winner_team ENUM('TEAM_A', 'TEAM_B') NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS match_teams (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  match_id INT UNSIGNED NOT NULL,
  team_label ENUM('TEAM_A', 'TEAM_B') NOT NULL,
  player1_id INT UNSIGNED NOT NULL,
  player2_id INT UNSIGNED NULL,
  UNIQUE KEY uq_match_team (match_id, team_label),
  CONSTRAINT fk_match_teams_match FOREIGN KEY (match_id) REFERENCES matches(id) ON DELETE CASCADE,
  CONSTRAINT fk_match_teams_player1 FOREIGN KEY (player1_id) REFERENCES players(id),
  CONSTRAINT fk_match_teams_player2 FOREIGN KEY (player2_id) REFERENCES players(id)
);

CREATE TABLE IF NOT EXISTS match_scores (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  match_id INT UNSIGNED NOT NULL,
  set_number TINYINT UNSIGNED NOT NULL,
  score_team_a TINYINT UNSIGNED NOT NULL,
  score_team_b TINYINT UNSIGNED NOT NULL,
  UNIQUE KEY uq_match_set (match_id, set_number),
  CONSTRAINT fk_match_scores_match FOREIGN KEY (match_id) REFERENCES matches(id) ON DELETE CASCADE
);
